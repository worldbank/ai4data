"""Test file discovery and storage for the metadata reviewer."""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from pydantic import ValidationError

from ai4data.data_snapshot.metadata_reviewer import storage
from ai4data.data_snapshot.metadata_reviewer.storage import (
    ReviewItem,
    discover_review_items,
    load_review_records,
    metadata_values_equal,
    save_reviewed,
)


def _write_json(path: Path, value: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value), encoding="utf-8")


def test_discovery_matches_exact_stems_and_warns_for_unmatched_files(
    tmp_path: Path,
) -> None:
    """Match flat and nested outputs without imposing research folder names."""

    snapshots = tmp_path / "snapshots"
    generated = tmp_path / "metadata"
    reviewed = tmp_path / "reviewed"
    first_snapshot = snapshots / "alpha.png"
    second_snapshot = snapshots / "reports" / "beta.JPG"
    unmatched_snapshot = snapshots / "missing_metadata.webp"
    for path in (first_snapshot, second_snapshot, unmatched_snapshot):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(b"png")
    _write_json(generated / "alpha.json", {})
    _write_json(generated / "reports" / "beta.json", {})
    _write_json(generated / "orphan.json", {})
    _write_json(generated / "alpha_metadata.json", {})
    existing_reviewed = reviewed / "elsewhere" / "beta.json"
    _write_json(existing_reviewed, {"title": "Reviewed"})
    _write_json(reviewed / "missing_metadata.json", {})

    result = discover_review_items(snapshots, generated, reviewed)

    assert [item.snapshot_id for item in result.items] == ["alpha", "beta"]
    assert result.items[0].reviewed_path == reviewed / "alpha.json"
    assert result.items[1].reviewed_path == existing_reviewed
    assert result.items[1].reviewed
    assert any("missing_metadata.webp" in warning for warning in result.warnings)
    assert any("orphan.json" in warning for warning in result.warnings)
    assert any("alpha_metadata.json" in warning for warning in result.warnings)
    assert any("Orphan reviewed metadata" in warning for warning in result.warnings)

    existing_reviewed.unlink()
    assert discover_review_items(snapshots, generated, reviewed).items[
        1
    ].reviewed_path == (reviewed / "reports" / "beta.json")


@pytest.mark.parametrize("kind", ["snapshot", "generated", "reviewed"])
def test_duplicate_stems_are_fatal(tmp_path: Path, kind: str) -> None:
    """Reject ambiguous matches in every input and output index."""

    snapshots = tmp_path / "snapshots"
    generated = tmp_path / "metadata"
    reviewed = tmp_path / "reviewed"
    snapshot = snapshots / "same.png"
    snapshot.parent.mkdir(parents=True)
    snapshot.write_bytes(b"png")
    _write_json(generated / "same.json", {})
    _write_json(reviewed / "same.json", {})
    if kind == "snapshot":
        (snapshots / "same.jpg").write_bytes(b"jpg")
    else:
        root = generated if kind == "generated" else reviewed
        _write_json(root / "nested" / "same.json", {})

    with pytest.raises(ValueError, match=f"Duplicate {kind} ID 'same'"):
        discover_review_items(snapshots, generated, reviewed)


def test_existing_reviewed_is_the_working_record(tmp_path: Path) -> None:
    """Load generated as reference and existing reviewed as an independent draft."""

    generated_path = tmp_path / "generated.json"
    reviewed_path = tmp_path / "reviewed.json"
    _write_json(generated_path, {"title": "Generated"})
    _write_json(reviewed_path, {"title": "Reviewed"})
    item = ReviewItem("sample", tmp_path / "sample.png", generated_path, reviewed_path)

    generated, working = load_review_records(item)
    working["title"] = "Changed again"

    assert generated == {"title": "Generated"}
    assert json.loads(reviewed_path.read_text(encoding="utf-8")) == {
        "title": "Reviewed"
    }


def test_comparison_treats_object_nulls_as_missing() -> None:
    """Ignore null object fields without collapsing invalid empty objects."""

    assert metadata_values_equal({"title": None}, {})
    assert metadata_values_equal(
        {"variables": [{"name": "Population", "unit": None}]},
        {"variables": [{"name": "Population"}]},
    )
    assert not metadata_values_equal({"project": {"name": None}}, {})
    assert not metadata_values_equal(["A", "B"], ["B", "A"])


def test_save_is_canonical_atomic_and_never_changes_generated(tmp_path: Path) -> None:
    """Write canonical reviewed JSON while leaving generated bytes unchanged."""

    generated_path = tmp_path / "metadata" / "sample.json"
    reviewed_path = tmp_path / "reviewed" / "reports" / "sample.json"
    _write_json(generated_path, {"title": "Generated"})
    original_generated = generated_path.read_bytes()
    item = ReviewItem("sample", tmp_path / "sample.png", generated_path, reviewed_path)

    metadata = save_reviewed(
        item,
        {
            "title": "  Reviewed title  ",
            "panel_titles": ["A", "A", "B"],
            "provenance": None,
        },
    )

    assert metadata.title == "Reviewed title"
    assert json.loads(reviewed_path.read_text(encoding="utf-8")) == {
        "title": "Reviewed title",
        "panel_titles": ["A", "B"],
    }
    assert reviewed_path.read_text(encoding="utf-8").endswith("\n")
    assert generated_path.read_bytes() == original_generated
    assert item.reviewed
    assert not list(reviewed_path.parent.glob("*.tmp"))


def test_invalid_save_preserves_existing_reviewed(tmp_path: Path) -> None:
    """Validate before writing so an invalid edit cannot damage existing reviewed."""

    generated_path = tmp_path / "generated.json"
    reviewed_path = tmp_path / "reviewed.json"
    _write_json(generated_path, {})
    _write_json(reviewed_path, {"title": "Existing reviewed"})
    original_reviewed = reviewed_path.read_bytes()
    item = ReviewItem("sample", tmp_path / "sample.png", generated_path, reviewed_path)

    with pytest.raises(ValidationError):
        save_reviewed(item, {"variables": [{}]})

    assert reviewed_path.read_bytes() == original_reviewed


def test_generated_and_reviewed_paths_cannot_overlap(tmp_path: Path) -> None:
    """Reject root and file configurations that could overwrite generated data."""

    snapshots = tmp_path / "snapshots"
    generated = tmp_path / "metadata"
    snapshots.mkdir()
    generated.mkdir()

    with pytest.raises(ValueError, match="must not overlap"):
        discover_review_items(snapshots, generated, generated / "reviewed")

    generated_path = generated / "same.json"
    _write_json(generated_path, {})
    item = ReviewItem("same", tmp_path / "same.png", generated_path, generated_path)
    with pytest.raises(ValueError, match="cannot overwrite"):
        save_reviewed(item, {})


@pytest.mark.parametrize("relation", ["same", "child", "parent", "symlink"])
@pytest.mark.parametrize("input_kind", ["snapshots", "metadata"])
def test_reviewed_root_must_be_separate(
    tmp_path: Path, relation: str, input_kind: str
) -> None:
    """Reject aliases and overlapping roots before creating output directories."""
    snapshots = tmp_path / "snapshots"
    generated = tmp_path / "metadata"
    snapshots.mkdir()
    generated.mkdir()
    root = tmp_path / input_kind
    reviewed = {
        "same": root,
        "child": root / "reviewed",
        "parent": tmp_path,
        "symlink": tmp_path / "alias",
    }[relation]
    if relation == "symlink":
        reviewed.symlink_to(root, target_is_directory=True)
    with pytest.raises(ValueError, match="must not overlap"):
        discover_review_items(snapshots, generated, reviewed)


def test_failed_atomic_replace_preserves_reviewed_file(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Clean up the temporary file and retain existing data on write failure."""
    generated = tmp_path / "generated.json"
    reviewed = tmp_path / "reviewed.json"
    _write_json(generated, {"title": "Generated"})
    _write_json(reviewed, {"title": "Existing review"})
    item = ReviewItem("sample", tmp_path / "sample.png", generated, reviewed)

    def fail_replace(source: Path, destination: Path) -> None:
        raise OSError("simulated write failure")

    monkeypatch.setattr(storage.os, "replace", fail_replace)
    with pytest.raises(OSError, match="simulated write failure"):
        save_reviewed(item, {"title": "Edited"})
    assert json.loads(reviewed.read_text()) == {"title": "Existing review"}
    assert json.loads(generated.read_text()) == {"title": "Generated"}
    assert not list(tmp_path.glob(".*.tmp"))


@pytest.mark.parametrize("value", [[], {"variables": "invalid"}, {"unknown": "field"}])
def test_invalid_input_metadata_is_rejected(tmp_path: Path, value: object) -> None:
    """Reject malformed records before the structured editor can alter them."""
    generated = tmp_path / "generated.json"
    _write_json(generated, value)
    item = ReviewItem(
        "sample", tmp_path / "sample.png", generated, tmp_path / "review.json"
    )
    with pytest.raises(ValueError):
        load_review_records(item)
    assert json.loads(generated.read_text()) == value
